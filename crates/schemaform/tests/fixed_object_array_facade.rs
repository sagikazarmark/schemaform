    let minimal = node_with_binding(&form, "/minimal");
    let existing_minimal = row_instances(&form, minimal)[0].1;

    form.user().append_item(defaulted).unwrap();
    form.user()
        .insert_item_before(minimal, existing_minimal)
        .unwrap();

    assert_eq!(
        form.form_data(),
        &json!({ "defaulted": [{ "name": "New" }], "minimal": [{}, {}] })
    );
