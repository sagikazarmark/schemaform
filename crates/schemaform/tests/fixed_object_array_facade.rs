#[cfg_attr(
    all(target_arch = "wasm32", target_os = "unknown"),
    wasm_bindgen_test::wasm_bindgen_test
)]
#[cfg_attr(not(all(target_arch = "wasm32", target_os = "unknown")), test)]
fn generated_fixed_object_item_template_edits_nested_rows_and_submits() {
    let definition = FormDefinition::compile(json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "additionalProperties": false,
        "required": ["people"],
        "properties": {
            "people": {
                "type": "array",
                "title": "People",
                "items": {
                    "type": "object",
                    "title": "Person",
                    "additionalProperties": false,
                    "required": ["name", "address"],
                    "properties": {
                        "name": {
                            "type": "string",
                            "title": "Name",
                            "minLength": 3
                        },
                        "address": {
                            "type": "object",
                            "title": "Address",
                            "additionalProperties": false,
                            "required": ["city"],
                            "properties": {
                                "city": {
                                    "type": "string",
                                    "title": "City",
                                    "minLength": 3
                                }
                            }
                        }
                    }
                }
            }
        }
    }))
    .expect("fixed-object array items should compile");

    let root = definition.node(definition.root()).unwrap();
    let array_id = root.children().next().expect("the array should exist");
    let array = definition.node(array_id).unwrap();
    assert_eq!(array.semantic_kind(), Some(SemanticKind::HomogeneousArray));
    assert_eq!(array.binding().map(JsonPointer::as_str), Some("/people"));

    let template_id = array
        .children()
        .next()
        .expect("the generated item template should exist");
    let template = definition.node(template_id).unwrap();
    assert_eq!(template.kind(), DefinitionNodeKind::AutoGeneratedLayout);
    assert_eq!(template.semantic_kind(), Some(SemanticKind::FixedObject));
    assert_eq!(template.binding().map(JsonPointer::as_str), Some(""));
    assert_eq!(template.label(), "Person");

    let template_children = template
        .children()
        .map(|id| definition.node(id).unwrap())
        .collect::<Vec<_>>();
    let name = template_children
        .iter()
        .find(|node| {
            node.binding()
                .is_some_and(|binding| binding.as_str() == "/name")
        })
        .expect("the relative name control should exist");
    let address = template_children
        .iter()
        .find(|node| {
            node.binding()
                .is_some_and(|binding| binding.as_str() == "/address")
        })
        .expect("the relative nested object should exist");
    let city = address
        .children()
        .next()
        .and_then(|id| definition.node(id))
        .expect("the relative city control should exist");
    assert_eq!(name.semantic_kind(), Some(SemanticKind::String));
    assert_eq!(
        city.binding().map(JsonPointer::as_str),
        Some("/address/city")
    );

    let duplicate = json!({ "name": "Ada", "address": { "city": "Rome" } });
    let mut form = definition
        .form(json!({ "people": [duplicate.clone(), duplicate] }))
        .finding_visibility(FindingVisibilityPolicy::new(
            FindingVisibility::Immediate,
            FindingVisibility::Immediate,
        ))
        .build()
        .unwrap();
    let array = node_with_binding(&form, "/people");
    let rows = form.node(array).unwrap().children().collect::<Vec<_>>();
    assert_eq!(rows.len(), 2);
    assert_ne!(
        rows[0], rows[1],
        "duplicate-valued rows need distinct identity"
    );
    assert_eq!(
        form.node(rows[0])
            .unwrap()
            .binding()
            .unwrap()
            .pointer()
            .as_str(),
        "/people/0"
    );
    assert_eq!(
        form.node(rows[1])
            .unwrap()
            .binding()
            .unwrap()
            .pointer()
            .as_str(),
        "/people/1"
    );

    let second_city = descendant_with_binding(&form, rows[1], "/people/1/address/city");
    form.user().input_text(second_city, "Li").unwrap();
    assert!(
        form.node(second_city)
            .unwrap()
            .validation_findings()
            .any(|finding| {
                finding.code() == "minLength"
                    && finding.instance_location().as_str() == "/people/1/address/city"
            })
    );
    form.user().input_text(second_city, "Paris").unwrap();

    let preparation = form.prepare_submission();
    let SubmissionOutcome::Ready(snapshot) = preparation.outcome() else {
        panic!("the corrected fixed-object rows should submit")
    };
    assert_eq!(
        snapshot.form_data(),
        &json!({
            "people": [
                { "name": "Ada", "address": { "city": "Rome" } },
                { "name": "Ada", "address": { "city": "Paris" } }
            ]
        })
    );
}

#[cfg_attr(
    all(target_arch = "wasm32", target_os = "unknown"),
    wasm_bindgen_test::wasm_bindgen_test
)]
#[cfg_attr(not(all(target_arch = "wasm32", target_os = "unknown")), test)]
fn duplicate_fixed_object_rows_keep_descendant_state_through_structural_commands() {
    let definition = FormDefinition::compile(json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "additionalProperties": false,
        "required": ["rows"],
        "properties": {
            "rows": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": false,
                    "default": { "amount": 2, "address": { "city": "Seed" } },
                    "required": ["amount", "address"],
                    "properties": {
                        "amount": { "type": "number" },
                        "address": {
                            "type": "object",
                            "additionalProperties": false,
                            "required": ["city"],
                            "properties": {
                                "city": { "type": "string" }
                            }
                        }
                    }
                }
            }
        }
    }))
    .unwrap();
    let duplicate = json!({ "amount": 1, "address": { "city": "Rome" } });
    let mut form = definition
        .form(json!({ "rows": [duplicate.clone(), duplicate] }))
        .finding_visibility(FindingVisibilityPolicy::new(
            FindingVisibility::Immediate,
            FindingVisibility::Immediate,
        ))
        .build()
        .unwrap();
    let array = node_with_binding(&form, "/rows");
    let initial = row_instances(&form, array);
    let logical_row = initial[1];
    let amount = descendant_with_binding(&form, logical_row.0, "/rows/1/amount");
    let city = descendant_with_binding(&form, logical_row.0, "/rows/1/address/city");
    form.user().input_text(amount, "not a number").unwrap();
    form.user().blur(amount).unwrap();
    form.apply_external_findings(ExternalFindingBatch::new(
        "server",
        form.view().data_revision(),
        [ExternalFinding::blocking(
            "review-city",
            JsonPointer::parse("/rows/1/address/city").unwrap(),
            json!({}),
        )],
    ))
    .unwrap();

    let moved = form.user().move_item_up(array, logical_row.1).unwrap();
    assert_eq!(row_instances(&form, array), vec![logical_row, initial[0]]);
    let moved_amount = form
        .node(amount)
        .expect("the descendant identity should move");
    assert_eq!(
        moved_amount.binding().unwrap().pointer().as_str(),
        "/rows/0/amount"
    );
    assert_eq!(moved_amount.edit_buffer(), Some("not a number"));
    assert!(moved_amount.parse_blocker().is_some());
    assert!(moved_amount.is_touched());
    let moved_city = form.node(city).expect("the nested identity should move");
    assert_eq!(
        moved_city.binding().unwrap().pointer().as_str(),
        "/rows/0/address/city"
    );
    assert_eq!(
        moved_city
            .external_findings()
            .next()
            .expect("the descendant finding should follow its row")
            .1
            .instance_location()
            .as_str(),
        "/rows/0/address/city"
    );
    assert_transition_contains_row_subtree(&form, &moved, logical_row.0);
    assert_transition_contains_row_subtree(&form, &moved, initial[0].0);

    form.user().move_item_down(array, logical_row.1).unwrap();
    assert_eq!(
        form.node(amount)
            .unwrap()
            .binding()
            .unwrap()
            .pointer()
            .as_str(),
        "/rows/1/amount"
    );

    let inserted = form
        .user()
        .insert_item_before(array, logical_row.1)
        .unwrap();
    let after_insert = row_instances(&form, array);
    assert_eq!(after_insert[0], initial[0]);
    assert_eq!(after_insert[2], logical_row);
    assert_eq!(
        form.form_data()["rows"][1],
        json!({ "amount": 2, "address": { "city": "Seed" } })
    );
    assert_transition_contains_row_subtree(&form, &inserted, after_insert[1].0);
    assert_transition_contains_row_subtree(&form, &inserted, logical_row.0);
    assert_eq!(
        form.node(amount).unwrap().edit_buffer(),
        Some("not a number")
    );

    let removed = form.user().remove_item(array, after_insert[1].1).unwrap();
    assert!(
        removed
            .removed()
            .any(|identity| identity == after_insert[1].0)
    );
    assert_eq!(row_instances(&form, array), initial);
    assert_eq!(
        form.node(amount).unwrap().edit_buffer(),
        Some("not a number")
    );

    let appended = form.user().append_item(array).unwrap();
    let after_append = row_instances(&form, array);
    assert_transition_contains_row_subtree(&form, &appended, after_append[2].0);
    form.user().remove_item(array, after_append[2].1).unwrap();
    assert_eq!(row_instances(&form, array), initial);
}

#[cfg_attr(
    all(target_arch = "wasm32", target_os = "unknown"),
    wasm_bindgen_test::wasm_bindgen_test
)]
#[cfg_attr(not(all(target_arch = "wasm32", target_os = "unknown")), test)]
fn arrays_nested_in_fixed_object_items_are_capability_blocking_through_references() {
    for (items, keyword_location) in [
        (
            json!({
                "type": "object",
                "properties": { "nested": { "type": "array", "items": { "type": "string" } } }
            }),
            "/properties/rows/items/properties/nested",
        ),
        (
            json!({ "$ref": "#/$defs/row" }),
            "/$defs/row/properties/nested",
        ),
    ] {
        let schema = json!({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "type": "object",
            "properties": { "rows": { "type": "array", "items": items } },
            "$defs": {
                "row": {
                    "type": "object",
                    "properties": {
                        "nested": { "type": "array", "items": { "type": "string" } }
                    }
                }
            }
        });
        let report = match FormDefinition::compile(schema.clone()) {
            Err(CompileError::Capability(report)) => report,
            Err(error) => panic!("unexpected compile error: {error}"),
            Ok(_) => panic!("nested arrays must not compile"),
        };
        let analysis = FormDefinition::compiler(schema.clone())
            .analyze()
            .expect("a nested array should remain a finite unsupported region");
        let repeated = FormDefinition::compiler(schema)
            .analyze()
            .expect("repeated nested-array analysis should be deterministic");
        assert_eq!(&report, analysis.capability_report());
        assert_eq!(analysis.capability_report(), repeated.capability_report());
        assert_eq!(
            analysis.definition().fingerprint(),
            repeated.definition().fingerprint()
        );
        let finding = report
            .findings()
            .find(|finding| finding.code() == "structure.array.nested")
            .expect("the nested-array finding should be reported");
        assert_eq!(finding.instance_location().as_str(), "/rows");
        assert_eq!(
            finding.keyword_location().pointer().as_str(),
            keyword_location
        );
        assert!(finding.is_blocking());

        let definition = analysis.into_parts().0;
        assert!(definition_contains_unsupported(&definition));
        let form_data = json!({ "rows": [{ "nested": ["preserved"] }] });
        let mut form = definition
            .create_form(form_data.clone())
            .expect("nested-array form data should remain constructible in lenient mode");
        assert!(matches!(
            form.prepare_submission().outcome(),
            SubmissionOutcome::Blocked(blockers)
                if blockers.iter().any(|blocker| matches!(
                    blocker,
                    SubmissionBlocker::Capability(finding)
                        if finding.code() == "structure.array.nested"
                ))
        ));
        assert_eq!(form.form_data(), &form_data);
    }
}

