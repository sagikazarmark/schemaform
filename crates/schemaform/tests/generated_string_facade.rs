#[test]
fn definition_fingerprints_frame_variable_length_semantics() {
    let left = FormDefinition::compile(json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "properties": {
            "a": { "type": "string", "title": "\u{0}b" }
        }
    }))
    .expect("the first data schema should compile");
    let right = FormDefinition::compile(json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "type": "object",
        "properties": {
            "a\u{0}": { "type": "string", "title": "b" }
        }
    }))
    .expect("the second data schema should compile");

    assert_ne!(left.fingerprint(), right.fingerprint());
}
